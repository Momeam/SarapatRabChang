CREATE TABLE IF NOT EXISTS users (
  id UUID PRIMARY KEY,
  email VARCHAR(320) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  username VARCHAR(100),
  role VARCHAR(50) NOT NULL DEFAULT 'User',
  full_name VARCHAR(120) NOT NULL DEFAULT '',
  phone VARCHAR(30) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS username VARCHAR(100),
  ADD COLUMN IF NOT EXISTS role VARCHAR(50) NOT NULL DEFAULT 'User';

CREATE UNIQUE INDEX IF NOT EXISTS users_username_unique
  ON users (username)
  WHERE username IS NOT NULL;

CREATE TABLE IF NOT EXISTS sessions (
  token_hash CHAR(64) PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS sessions_user_id
  ON sessions (user_id);

CREATE TABLE IF NOT EXISTS profile_freelance (
  freelance_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_card_number UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  first_name VARCHAR(100) NOT NULL,
  bank_account_info VARCHAR(100),
  kyc_status TEXT
);

CREATE INDEX IF NOT EXISTS profile_freelance_id_card_number
  ON profile_freelance (id_card_number);

CREATE TABLE IF NOT EXISTS profile_client (
  client_id UUID PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  tax_id VARCHAR(50),
  address TEXT
);

CREATE TABLE IF NOT EXISTS service_category (
  category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS service_listing (
  listing_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  freelance_id INTEGER NOT NULL
    REFERENCES profile_freelance (freelance_id) ON DELETE CASCADE,
  category_id INTEGER NOT NULL
    REFERENCES service_category (category_id),
  title VARCHAR(200) NOT NULL,
  status VARCHAR(50) NOT NULL
);

CREATE INDEX IF NOT EXISTS service_listing_freelance_id
  ON service_listing (freelance_id);

CREATE INDEX IF NOT EXISTS service_listing_category_id
  ON service_listing (category_id);

CREATE TABLE IF NOT EXISTS service_package (
  package_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  listing_id INTEGER NOT NULL REFERENCES service_listing (listing_id) ON DELETE CASCADE,
  tier_name VARCHAR(50) NOT NULL,
  price NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
  duration_days INTEGER NOT NULL CHECK (duration_days >= 0)
);

CREATE INDEX IF NOT EXISTS service_package_listing_id
  ON service_package (listing_id);

CREATE TABLE IF NOT EXISTS quotations (
  quotation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id UUID NOT NULL REFERENCES profile_client (client_id),
  freelance_id INTEGER NOT NULL REFERENCES profile_freelance (freelance_id),
  total_price NUMERIC(12, 2) NOT NULL CHECK (total_price >= 0),
  status VARCHAR(50) NOT NULL
);

CREATE INDEX IF NOT EXISTS quotations_client_id
  ON quotations (client_id);

CREATE INDEX IF NOT EXISTS quotations_freelance_id
  ON quotations (freelance_id);

CREATE TABLE IF NOT EXISTS orders (
  order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id UUID NOT NULL REFERENCES profile_client (client_id),
  listing_id INTEGER NOT NULL REFERENCES service_listing (listing_id),
  package_id INTEGER NOT NULL REFERENCES service_package (package_id),
  total_amount NUMERIC(12, 2) NOT NULL CHECK (total_amount >= 0),
  escrow_status VARCHAR(50) NOT NULL,
  order_status VARCHAR(50) NOT NULL
);

CREATE INDEX IF NOT EXISTS orders_client_id
  ON orders (client_id);

CREATE INDEX IF NOT EXISTS orders_listing_id
  ON orders (listing_id);

CREATE INDEX IF NOT EXISTS orders_package_id
  ON orders (package_id);

CREATE TABLE IF NOT EXISTS milestones (
  milestone_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES orders (order_id),
  milestone_title VARCHAR(200) NOT NULL,
  amount NUMERIC(12, 2) NOT NULL CHECK (amount >= 0),
  status VARCHAR(50) NOT NULL
);

CREATE INDEX IF NOT EXISTS milestones_order_id
  ON milestones (order_id);

CREATE TABLE IF NOT EXISTS submissions (
  submission_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  milestone_id INTEGER NOT NULL REFERENCES milestones (milestone_id),
  work_file_url TEXT NOT NULL,
  note TEXT,
  status VARCHAR(50) NOT NULL
);

CREATE INDEX IF NOT EXISTS submissions_milestone_id
  ON submissions (milestone_id);

CREATE TABLE IF NOT EXISTS reviews (
  review_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES orders (order_id),
  reviewer_id UUID NOT NULL REFERENCES users (id),
  rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment TEXT
);

CREATE INDEX IF NOT EXISTS reviews_order_id
  ON reviews (order_id);

CREATE INDEX IF NOT EXISTS reviews_reviewer_id
  ON reviews (reviewer_id);

CREATE TABLE IF NOT EXISTS disputes (
  dispute_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES orders (order_id),
  raised_by_user_id UUID NOT NULL REFERENCES users (id),
  reason TEXT NOT NULL,
  admin_decision TEXT,
  status VARCHAR(50) NOT NULL
);

CREATE INDEX IF NOT EXISTS disputes_order_id
  ON disputes (order_id);

CREATE INDEX IF NOT EXISTS disputes_raised_by_user_id
  ON disputes (raised_by_user_id);

CREATE TABLE IF NOT EXISTS bookings (
  id UUID PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES users (id),
  provider_id VARCHAR(80) NOT NULL,
  package_title VARCHAR(120) NOT NULL,
  price DECIMAL(10, 2) NOT NULL,
  service_date DATE NOT NULL,
  time_slot VARCHAR(60) NOT NULL,
  contact_name VARCHAR(120) NOT NULL,
  email VARCHAR(320) NOT NULL,
  phone VARCHAR(30) NOT NULL DEFAULT '',
  address VARCHAR(500) NOT NULL,
  note VARCHAR(500) NOT NULL DEFAULT '',
  status VARCHAR(32) NOT NULL DEFAULT 'pending_payment'
    CHECK (status IN ('pending_payment', 'paid', 'in_progress', 'delivered', 'completed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS bookings_user_id_created_at
  ON bookings (user_id, created_at);
